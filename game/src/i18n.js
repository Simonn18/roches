function initialLanguage() {
  try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'fr'; } catch (_) { return 'fr'; }
}
currentLanguage = initialLanguage();

function notifyLanguageChange() {
  for (const listener of languageListeners) {
    try { listener(currentLanguage); } catch (_) { /* non bloquant */ }
  }
}

export function onLangueChange(listener) {
  if (typeof listener !== 'function') return () => {};
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

function normalise(code) { return code === 'en' ? 'en' : 'fr'; }

export function lireLangue() { return currentLanguage; }

export function enregistrerLangue(code) {
  const next = normalise(code);
  currentLanguage = next;
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = next;
  }
  try { localStorage.setItem(STORAGE_KEY, next); } catch (_) { /* non bloquant */ }
  notifyLanguageChange();
  return next;
}

function translateDynamic(value, lang) {
  if (lang !== 'en' || typeof value !== 'string') return value;
  let match = value.match(/^Objectif\s*:\s*(.*)$/);
  if (match) return `Objective: ${traduire(match[1], lang)}`;
  match = value.match(/^ÉTAPE\s+(\d+\/\d+)$/);
  if (match) return `STEP ${match[1]}`;
  match = value.match(/^(\d+)\/(\d+) cases maîtrisées$/);
  if (match) return `${match[1]}/${match[2]} levels mastered`;
  match = value.match(/^(\d+)\/(\d+) étapes maîtrisées$/);
  if (match) return `${match[1]}/${match[2]} steps mastered`;
  match = value.match(/^(\d+)\/(\d+) puzzles résolus$/);
  if (match) return `${match[1]}/${match[2]} puzzles solved`;
  match = value.match(/^✓\s*(.*?) acheté — résous la position$/);
  if (match) return `✓ ${traduire(match[1], lang)} bought — solve the position`;
  match = value.match(/^([^·]+)\s+·\s+valeur\s+(\d+)$/);
  if (match) return `${traduire(match[1], lang)} · value ${match[2]}`;
  match = value.match(/^recharge\s+(\d+)$/);
  if (match) return `cooldown ${match[1]}`;
  match = value.match(/^case gelée\s+(\d+) tour\(s\)$/);
  if (match) return `frozen square ${match[1]} turn(s)`;
  match = value.match(/^Trophées\s*:/);
  if (match) return value.replace(/^Trophées\s*:/, 'Trophies:');
  match = value.match(/^Au tour de (.+)$/);
  if (match) {
    const playerKey = match[1].replace(/^l[’']adversaire$/i, 'Adversaire');
    return `Turn of ${traduire(playerKey, lang)}`;
  }
  match = value.match(/^ÉCHEC — (le roi adverse est menacé|ton roi est menacé)$/);
  if (match) return `CHECK — ${match[1] === 'le roi adverse est menacé' ? 'the opposing king is threatened' : 'your king is threatened'}`;
  match = value.match(/^Clic droit sur la tour .* \((\d+) écus\).*$/);
  if (match) return `Right-click the rook (or left-click it, then UPGRADE) to open the panel, then click the Fortress card (${match[1]} coins).`;
  match = value.match(/^La Ruée que tu viens d'utiliser se recharge en (\d+) tours\..*$/);
  if (match) return `The Charge you just used cools down in ${match[1]} turns. Each piece accepts at most 2 upgrades, lost if it is captured. Click CONTINUE.`;
  match = value.match(/^(Plafond (?:30|15) écus|Illimité) × (Déplacement \+2 écus|Élim\. ×2 écus)$/);
  if (match) return `${traduire(match[1], lang)} × ${traduire(match[2], lang)}`;
  match = value.match(/^Le serveur de jeu ne répond pas \((.*?)\)\. Nouvelle tentative…$/);
  if (match) {
    const detail = match[1]
      .replace(/network request failed|fetch failed/i, 'network request failed')
      .replace(/timeout|timed out/i, 'timeout');
    return `The game server is not responding (${detail}). Retrying…`;
  }
  match = value.match(/^Trop de tentatives\. Réessaie dans (.+)\.$/);
  if (match) return `Too many attempts. Try again in ${match[1]}.`;
  match = value.match(/^Si cette adresse est associée à un compte, un lien a été envoyé ✓$/);
  if (match) return 'If this address is associated with an account, a link was sent ✓';
  return value;
}

export function traduire(value, lang = lireLangue()) {
  if (typeof value !== 'string') return value;
  const code = normalise(lang);
  return code === 'en' ? (TEXT.en[value] || translateDynamic(value, code)) : value;
}

const textSources = new WeakMap();
const attributeSources = new WeakMap();

export function appliquerTraductions(root, lang = lireLangue()) {
  if (!root || typeof document === 'undefined') return;
  if (root === document.documentElement || root === document.body) {
    document.documentElement.lang = normalise(lang);
  }
  const translateNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      if (!textSources.has(node)) textSources.set(node, node.nodeValue);
      const original = textSources.get(node);
      const trimmed = original.trim();
      if (!trimmed) return;
      const translated = traduire(trimmed, lang);
      node.nodeValue = original.replace(trimmed, translated);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    let attrs = attributeSources.get(node);
    if (!attrs) { attrs = {}; attributeSources.set(node, attrs); }
    for (const attr of ['placeholder', 'aria-label', 'title']) {
      if (node.hasAttribute(attr)) {
        if (attrs[attr] == null) attrs[attr] = node.getAttribute(attr);
        node.setAttribute(attr, traduire(attrs[attr], lang));
      }
    }
    for (const child of node.childNodes) translateNode(child);
  };
  translateNode(root);
}
